#!/usr/bin/env python3
"""Build the second Gowin pROM image from the official 2048 x 32 hex format.

The first image remains the unmodified official Gowin_pROM IP. Before writing
anything, validate every original INIT_RAM block against logoT.hex. Neither
synthesis nor simulation depends on runtime $readmemh or a working directory.
"""

import argparse
import hashlib
from pathlib import Path
import re


DEPTH = 2048
LANES = 4
BLOCKS = 64
BYTES_PER_BLOCK = 32


def read_image(path):
    words = []
    for line_number, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not re.fullmatch(r"[0-9a-fA-F]{8}", line):
            raise ValueError(f"{path}:{line_number}: expected one 32-bit hex word")
        words.append(int(line, 16))
    if len(words) != DEPTH:
        raise ValueError(f"{path}: expected {DEPTH} words, got {len(words)}")
    return words


def init_block(words, lane, block):
    # INIT_RAM_00 bits [7:0] store byte lane 'lane' of address zero.
    return sum(
        ((words[block * BYTES_PER_BLOCK + offset] >> (lane * 8)) & 0xFF)
        << (offset * 8)
        for offset in range(BYTES_PER_BLOCK)
    )


def verify_official_rom(path, words):
    pattern = r"defparam\s+prom_inst_([0-3])\.INIT_RAM_([0-9A-Fa-f]{2})\s*=\s*256'h([0-9A-Fa-f]+)\s*;"
    constants = re.findall(pattern, path.read_text(encoding="utf-8-sig"))
    found = {}
    for lane_text, block_text, value_text in constants:
        key = int(lane_text), int(block_text, 16)
        if key in found:
            raise ValueError(f"{path}: duplicate INIT_RAM block {key}")
        found[key] = int(value_text, 16)
    expected_keys = {(lane, block) for lane in range(LANES) for block in range(BLOCKS)}
    if set(found) != expected_keys:
        raise ValueError(f"{path}: expected 256 byte-lane INIT_RAM blocks")
    for (lane, block), actual in found.items():
        if actual != init_block(words, lane, block):
            raise ValueError(
                f"{path}: prom_inst_{lane}.INIT_RAM_{block:02X} differs from logoT.hex; "
                "regenerate the official IP with Gowin IP Core Generator first"
            )


def image_digest(words):
    data = b"".join(word.to_bytes(4, "big") for word in words)
    return hashlib.sha256(data).hexdigest()


def generate_verilog(t_words, s_words):
    lines = [
        "// Generated by tools/generate_display_rom.py; edit the hex assets instead.",
        f"// logoT.hex data SHA-256: {image_digest(t_words)}",
        f"// logoS.hex data SHA-256: {image_digest(s_words)}",
        "// Two 2048 x 32 images use eight 16 Kbit BSRAM pROM primitives.",
        "// READ_MODE=0 is a synchronous, one-rising-edge read (official IP setting).",
        "// The caller must change image_sel only at a complete PWM-cycle boundary.",
        "",
        "module display_rom (",
        "    input wire clk,",
        "    input wire reset,",
        "    input wire [10:0] ad,",
        "    input wire image_sel,",
        "    output wire [31:0] dout",
        ");",
        "    wire [31:0] image_t_data;",
        "    wire [31:0] image_s_data;",
        "",
        "    // Keep the manufacturer's original logoT IP and its timing unchanged.",
        "    Gowin_pROM image_t (",
        "        .dout(image_t_data), .clk(clk), .oce(1'b1), .ce(1'b1),",
        "        .reset(reset), .ad(ad)",
        "    );",
        "    Gowin_pROM_S image_s (",
        "        .dout(image_s_data), .clk(clk), .oce(1'b1), .ce(1'b1),",
        "        .reset(reset), .ad(ad)",
        "    );",
        "",
        "    // Both ROMs read continuously, so image changes need no extra cycle.",
        "    assign dout = image_sel ? image_s_data : image_t_data;",
        "endmodule",
        "",
        "module Gowin_pROM_S (dout, clk, oce, ce, reset, ad);",
        "    output wire [31:0] dout;",
        "    input wire clk, oce, ce, reset;",
        "    input wire [10:0] ad;",
    ]
    for lane in range(LANES):
        lines += [
            "",
            f"    wire [23:0] unused_{lane};",
            f"    pROM prom_inst_{lane} (",
            f"        .DO({{unused_{lane}, dout[{lane * 8 + 7}:{lane * 8}]}}),",
            "        .CLK(clk), .OCE(oce), .CE(ce), .RESET(reset),",
            "        .AD({ad, 3'b000})",
            "    );",
            f"    defparam prom_inst_{lane}.READ_MODE = 1'b0;",
            f"    defparam prom_inst_{lane}.BIT_WIDTH = 8;",
            f'    defparam prom_inst_{lane}.RESET_MODE = "SYNC";',
        ]
        for block in range(BLOCKS):
            lines.append(
                f"    defparam prom_inst_{lane}.INIT_RAM_{block:02X} = "
                f"256'h{init_block(s_words, lane, block):064X};"
            )
    lines += ["endmodule", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated output without writing")
    parser.add_argument("--project-dir", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    src = args.project_dir.resolve() / "src"
    t_words = read_image(src / "logoT.hex")
    s_words = read_image(src / "logoS.hex")
    verify_official_rom(src / "gowin_prom" / "gowin_prom.v", t_words)
    expected = generate_verilog(t_words, s_words)
    output = src / "display_rom.v"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != expected:
            raise SystemExit("display_rom.v is stale: run tools/generate_display_rom.py")
        print("PASS: official logoT INITs and generated logoS INITs match both 2048 x 32 images")
    else:
        output.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {output} (8 BSRAM total, original logoT IP preserved)")


if __name__ == "__main__":
    main()
