    ("ADSR_TOUCH", "ADSR,TOUCH,", None), ("ADSR_SENSOR", "ADSR,SENSOR,", None),
    ("ADSR_RESET_TOUCH", "ADSR_RESET,TOUCH", 16),
    ("ADSR_RESET_SENSOR", "ADSR_RESET,SENSOR", 17),
    ("TEST32", "TEST32", 6), ("GUITAR", "GUITAR", 6),
    ("TONE_SET", "TONE,", 6), ("VIBRATO_SET", "VIBRATO,", 9),
    ("BANK_SET", "BANK,", 6), ("MAP_QUERY", "MAP?", 4),
    ("MAP_RESET", "MAP_RESET", 9), ("MAP_SET", "MAP,", 8),
    ("SONG_BEGIN", "SONG_BEGIN,", None), ("SONG_NOTE", "SONG_NOTE,", None),
    ("SONG_CHORD", "SONG_CHORD,", None), ("SONG_END", "SONG_END", 8),
    ("PLAY", "PLAY", 4), ("AUDITION", "AUDITION", 8),
